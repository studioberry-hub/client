// Генератор тестового скина 64×64 с различимыми цветами по частям тела
/** Создаёт data-URL PNG-скина для офлайн-демо */
export function createTestSkinDataUrl(): string {
  const canvas = document.createElement("canvas");
  canvas.width = 64;
  canvas.height = 64;
  const ctx = canvas.getContext("2d");
  if (!ctx) {
    throw new Error("Canvas 2D недоступен");
  }

  ctx.clearRect(0, 0, 64, 64);

  const fill = (x: number, y: number, w: number, h: number, color: string): void => {
    ctx.fillStyle = color;
    ctx.fillRect(x, y, w, h);
  };

  // ===== Базовый слой =====
  // Голова
  fill(8, 0, 8, 8, "#c69c6d");
  fill(16, 0, 8, 8, "#a67c52");
  fill(0, 8, 8, 8, "#8b6914");
  fill(8, 8, 8, 8, "#e8c4a0");
  fill(16, 8, 8, 8, "#d4a574");
  fill(24, 8, 8, 8, "#b88860");

  // Туловище
  fill(20, 16, 8, 4, "#3b8526");
  fill(28, 16, 8, 4, "#2d6a1e");
  fill(16, 20, 4, 12, "#1e4d14");
  fill(20, 20, 8, 12, "#55a630");
  fill(28, 20, 4, 12, "#40916c");
  fill(32, 20, 8, 12, "#2d6a4f");

  // Правая рука (classic 4px)
  fill(44, 16, 4, 4, "#264653");
  fill(48, 16, 4, 4, "#1d3557");
  fill(40, 20, 4, 12, "#1b4332");
  fill(44, 20, 4, 12, "#457b9d");
  fill(48, 20, 4, 12, "#2a6f97");
  fill(52, 20, 4, 12, "#1d3557");

  // Левая рука (MC 1.8+ регион)
  fill(36, 48, 4, 4, "#264653");
  fill(40, 48, 4, 4, "#1d3557");
  fill(32, 52, 4, 12, "#1b4332");
  fill(36, 52, 4, 12, "#457b9d");
  fill(40, 52, 4, 12, "#2a6f97");
  fill(44, 52, 4, 12, "#1d3557");

  // Правая нога
  fill(4, 16, 4, 4, "#22223b");
  fill(8, 16, 4, 4, "#1a1a2e");
  fill(0, 20, 4, 12, "#0f0f1a");
  fill(4, 20, 4, 12, "#4a4e69");
  fill(8, 20, 4, 12, "#3d405b");
  fill(12, 20, 4, 12, "#22223b");

  // Левая нога
  fill(20, 48, 4, 4, "#22223b");
  fill(24, 48, 4, 4, "#1a1a2e");
  fill(16, 52, 4, 12, "#0f0f1a");
  fill(20, 52, 4, 12, "#4a4e69");
  fill(24, 52, 4, 12, "#3d405b");
  fill(28, 52, 4, 12, "#22223b");

  // ===== Overlay (шапка, куртка и т.д.) — полупрозрачные акценты =====
  fill(40, 0, 8, 8, "rgba(255, 200, 0, 0.7)");
  fill(48, 0, 8, 8, "rgba(200, 150, 0, 0.7)");
  fill(32, 8, 8, 8, "rgba(180, 120, 0, 0.7)");
  fill(40, 8, 8, 8, "rgba(255, 220, 50, 0.7)");
  fill(48, 8, 8, 8, "rgba(220, 170, 0, 0.7)");
  fill(56, 8, 8, 8, "rgba(180, 120, 0, 0.7)");

  fill(20, 32, 8, 4, "rgba(255, 80, 80, 0.6)");
  fill(28, 32, 8, 4, "rgba(200, 60, 60, 0.6)");
  fill(16, 36, 4, 12, "rgba(160, 40, 40, 0.6)");
  fill(20, 36, 8, 12, "rgba(255, 100, 100, 0.6)");
  fill(28, 36, 4, 12, "rgba(220, 80, 80, 0.6)");
  fill(32, 36, 8, 12, "rgba(180, 50, 50, 0.6)");

  // Правая рукав overlay
  fill(44, 32, 4, 4, "rgba(100, 180, 255, 0.6)");
  fill(48, 32, 4, 4, "rgba(80, 140, 220, 0.6)");
  fill(40, 36, 4, 12, "rgba(60, 120, 200, 0.6)");
  fill(44, 36, 4, 12, "rgba(120, 200, 255, 0.6)");
  fill(48, 36, 4, 12, "rgba(90, 160, 240, 0.6)");
  fill(52, 36, 4, 12, "rgba(70, 130, 210, 0.6)");

  // Левая рукав overlay (отдельный регион 52,48)
  fill(52, 48, 4, 4, "rgba(100, 180, 255, 0.6)");
  fill(56, 48, 4, 4, "rgba(80, 140, 220, 0.6)");
  fill(48, 52, 4, 12, "rgba(60, 120, 200, 0.6)");
  fill(52, 52, 4, 12, "rgba(120, 200, 255, 0.6)");
  fill(56, 52, 4, 12, "rgba(90, 160, 240, 0.6)");
  fill(60, 52, 4, 12, "rgba(70, 130, 210, 0.6)");

  // Штаны overlay
  fill(4, 32, 4, 4, "rgba(80, 80, 120, 0.6)");
  fill(8, 32, 4, 4, "rgba(60, 60, 100, 0.6)");
  fill(0, 36, 4, 12, "rgba(40, 40, 80, 0.6)");
  fill(4, 36, 4, 12, "rgba(100, 100, 160, 0.6)");
  fill(8, 36, 4, 12, "rgba(80, 80, 140, 0.6)");
  fill(12, 36, 4, 12, "rgba(60, 60, 120, 0.6)");

  fill(4, 48, 4, 4, "rgba(80, 80, 120, 0.6)");
  fill(8, 48, 4, 4, "rgba(60, 60, 100, 0.6)");
  fill(0, 52, 4, 12, "rgba(40, 40, 80, 0.6)");
  fill(4, 52, 4, 12, "rgba(100, 100, 160, 0.6)");
  fill(8, 52, 4, 12, "rgba(80, 80, 140, 0.6)");
  fill(12, 52, 4, 12, "rgba(60, 60, 120, 0.6)");

  // Прозрачный пиксель (54, 20) — эвристика classic vs slim (skinview3d)
  ctx.clearRect(54, 20, 1, 1);

  return canvas.toDataURL("image/png");
}
